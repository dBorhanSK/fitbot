  locked boolean not null default false,
  created_at timestamptz not null default now()
);

-- Locked channels can never be deleted or changed, by anyone, even from the dashboard.
create or replace function public.protect_locked_channels() returns trigger
language plpgsql as $$
begin
  if tg_op = 'DELETE' then
    if old.locked then
      raise exception 'locked required channel cannot be deleted';
    end if;
    return old;
  end if;
  if old.locked and (new.chat_ref is distinct from old.chat_ref or new.locked is distinct from true) then
    raise exception 'locked required channel cannot be modified';
  end if;
  return new;
end;
$$;
drop trigger if exists trg_protect_locked_channels on public.required_channels;
create trigger trg_protect_locked_channels
  before update or delete on public.required_channels
  for each row execute function public.protect_locked_channels();

